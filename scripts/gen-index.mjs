// Regenerates the per-folder barrels (src/lib/ui/<group>/index.ts) from the .svelte files on disk,
// so every component is exported by construction. `--check` exits 1 if any barrel is stale (CI).
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('../src/lib/ui/', import.meta.url).pathname;
const GROUPS = ['agents', 'blocks', 'components', 'illustrations', 'motion', 'screens', 'screens/shell'];
const check = process.argv.includes('--check');
let stale = 0;
const hasModuleTypes = (file) =>
	[...readFileSync(file, 'utf8').matchAll(/<script[^>]*\bmodule\b[^>]*>([\s\S]*?)<\/script>/g)].some((m) => /export\s+(type|interface)\s/.test(m[1]));

for (const group of GROUPS) {
	const dir = join(ROOT, group);
	const names = readdirSync(dir)
		.filter((f) => f.endsWith('.svelte') && !f.endsWith('.stories.svelte'))
		.map((f) => f.slice(0, -'.svelte'.length))
		.sort((a, b) => a.localeCompare(b));
	const body =
		'// Generated by scripts/gen-index.mjs — do not edit by hand (run `bun run gen:index`).\n' +
		names.map((n) => `export { default as ${n} } from './${n}.svelte';`).join('\n') +
		'\n' +
		// Module-script types collide across components (Agent, Card, Task…), so each gets its own namespace:
		// `import type { AgentGraphTypes } from 'officeui'` → `AgentGraphTypes.GNode`.
		names.filter((n) => hasModuleTypes(join(dir, n + '.svelte'))).map((n) => `export type * as ${n}Types from './${n}.svelte';`).join('\n') +
		'\n';
	// sub-groups are re-exported by their parent
	const sub = GROUPS.filter((g) => g.startsWith(group + '/')).map((g) => `export * from './${g.slice(group.length + 1)}/index';\n`);
	const out = body + sub.join('');
	const file = join(dir, 'index.ts');
	const cur = existsSync(file) ? readFileSync(file, 'utf8') : '';
	if (cur === out) continue;
	if (check) { console.error(`stale: ${group}/index.ts`); stale++; } else writeFileSync(file, out);
}
process.exit(stale ? 1 : 0);
